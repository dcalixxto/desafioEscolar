def get_questions(subject, difficulty):
    """Perguntas de um professor para um nível (sempre do tema dele)."""
    return COMPETITION_QUESTIONS.get(subject, {}).get(difficulty, [])


def questions_per_level():
    """Garante o formato do evento: cada matéria tem 5 perguntas de
    4 alternativas em cada um dos 4 níveis de desafio."""
    for subject, levels in COMPETITION_QUESTIONS.items():
        for diff, questions in levels.items():
            assert len(questions) == 5, (
                f"Nível '{diff}' de '{subject}' deve ter exatamente 5 perguntas (tem {len(questions)})."
            )
            for q in questions:
                assert len(q["options"]) == 4, f"Pergunta '{q['title']}' deve ter 4 alternativas."
                assert 0 <= q["correct_index"] < 4, f"Pergunta '{q['title']}' tem correct_index inválido."
                assert q["subject"] == SUBJECT_NAMES[subject], (
                    f"Pergunta '{q['title']}' está no banco de '{subject}' mas se declara '{q['subject']}'."
                )
    return len(COMPETITION_QUESTIONS)   # quantidade de matérias com banco completo
